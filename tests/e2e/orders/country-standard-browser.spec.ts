import { expect, test } from '@playwright/test'
import { loginThroughUi, syntheticUsers } from '../support/auth-helpers'
import { installBrowserGuards } from '../support/browser-guards'
import { execFileSync } from 'node:child_process'

function db(query: string) {
  if (process.env.BYL_E2E_DISPOSABLE !== 'true' || process.env.DB_CONNECTION !== 'sqlite') throw Error('Not isolated')
  return execFileSync('php', ['artisan', 'tinker', '--execute='+query], { env: process.env, encoding: 'utf8' }).trim()
}
test('country standard: order create/edit, KOL independent nationality and address', async ({page,context}) => {
  const guard = await installBrowserGuards(context,page)
  await page.setViewportSize({width:1440,height:900})
  await loginThroughUi(page, syntheticUsers().authorized)
  await page.goto('/customers/orders/create')
  const country=page.getByTestId('order-country')
  await expect(country).toBeVisible()
  await country.fill('nor')
  await page.getByRole('option',{name:/Norway \(NO\)/}).click()
  await expect(country).toHaveValue('Norway (NO)')
  await country.fill('Germany')
  await country.press('Enter')
  await expect(country).toHaveValue('Germany (DE)')
  await country.fill('EU')
  await country.press('Tab')
  await expect(country).toHaveAttribute('aria-invalid','true')
  await country.fill('挪威')
  await country.press('Tab')
  await expect(country).toHaveValue('Norway (NO)')
  console.log('COUNTRY_CREATE_UI_PASS')
  const orderId=db('$o=App\\Modules\\Orders\\Infrastructure\\Models\\Order::where("external_order_number","E2E-CUSTOMER-PRIVATE")->firstOrFail();$o->address()->create(["recipient_name"=>"Synthetic","phone"=>"5551234567","country"=>"Norway","city"=>"Oslo","province_state"=>"Oslo","address_line_1"=>"Synthetic Street","postal_code"=>"0001"]);echo $o->id;')
  await page.goto('/customers/orders/'+orderId)
  await expect(page.getByTestId('order-edit-country')).toHaveCount(0)
  await page.getByTestId('order-edit').click()
  const edit=page.getByTestId('order-edit-country')
  await expect(edit).toHaveValue('Norway (NO)')
  await edit.fill('Germany')
  await edit.press('Tab')
  await expect(edit).toHaveValue('Germany (DE)')
  await page.getByRole('button',{name:'保存订单',exact:true}).click()
  await expect(page.getByTestId('order-edit')).toBeVisible()
  expect(db('echo App\\Modules\\Orders\\Infrastructure\\Models\\Order::findOrFail('+orderId+')->address->country;')).toBe('DE')
  console.log('COUNTRY_EDIT_DB_PASS')
  await page.goto('/kol/library/create')
  const n=page.getByTestId('kol-nationality-country')
  const s=page.getByTestId('kol-shipping-country')
  await n.fill('New Zealand')
  await n.press('Tab')
  await s.fill('Norway')
  await s.press('Tab')
  await expect(n).toHaveValue('New Zealand (NZ)')
  await expect(s).toHaveValue('Norway (NO)')
  const kolId=db('$k=App\\Modules\\Kol\\Infrastructure\\Models\\Kol::create(["display_name"=>"Country UAT Synthetic","country_code"=>"NZ","shipping_country"=>"NO","status"=>"active","relationship_stage"=>"prospect"]);echo $k->id;')
  await page.goto('/kol/library/'+kolId+'/edit')
  await expect(n).toHaveValue('New Zealand (NZ)')
  await expect(s).toHaveValue('Norway (NO)')
  await s.fill('Mexico')
  await s.press('Tab')
  await expect(s).toHaveValue('Mexico (MX)')
  await expect(n).toHaveValue('New Zealand (NZ)')
  await expect(page.getByTestId('recipient-customs-field')).toBeVisible()
  console.log('COUNTRY_KOL_UI_PASS')
  await guard.assertClean()
})
