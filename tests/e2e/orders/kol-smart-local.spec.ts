import { expect, test } from '@playwright/test'
import { loginThroughUi, syntheticUsers } from '../support/auth-helpers'
import { installBrowserGuards } from '../support/browser-guards'

test('staff local onboarding and explicit shipping confirmation in disposable Dev', async ({context,page})=>{
 test.setTimeout(45000)
 const guard=await installBrowserGuards(context,page)
 await loginThroughUi(page,syntheticUsers().kolEmma)
 await page.goto('/kol/orders/create')
 await page.getByTestId('kol-smart-raw').fill('https://x.com/demo_browser_onboarding 12K\nFull Name: Synthetic Recipient\nCountry: US\nState: CA\nCity: Synthetic City\nAddress Line: 10 Demo Street\nPost Code: 01234\nPhone: 0005550100\nEmail: demo_browser@example.test\nProduct: E2E-SKU-0001\nCode: BROWSER20')
 await page.getByTestId('kol-smart-parse').click()
 await expect(page.getByTestId('kol-smart-preview')).toBeVisible()
 await expect(page.getByTestId('kol-smart-shape')).toHaveCount(0)
 await page.getByTestId('kol-smart-apply').click()
 await expect(page.getByTestId('kol-identity-select')).toHaveValue('demo_browser_onboarding')
 await page.getByTestId('kol-onboarding-start').click()
 await expect(page).toHaveURL(/\/kol\/library\/create\?onboarding_token=/)
 await expect(page.getByTestId('kol-onboarding-resume')).toBeVisible()
 await expect(page.locator('input[autocomplete="username"]')).toHaveValue('demo_browser_onboarding')
 await expect(page.getByTestId('kol-shipping-country')).toHaveValue('US')
 await expect(page.getByRole('button',{name:'保存 KOL'})).toBeVisible()
 // Local UAT uses the repository's fake AffiliateWP gateway. No provider calls.
 const fixturePassword='Dev'+syntheticUsers().kolEmma.password
 const fields=page.locator('input[autocomplete="new-password"]')
 await fields.nth(0).fill(fixturePassword)
 await fields.nth(1).fill(fixturePassword)
 await page.getByRole('button',{name:'保存 KOL'}).click()
 await expect(page).toHaveURL(/\/kol\/orders\/create\?/, {timeout:15000})
 await expect(page.getByTestId('kol-smart-order-review')).toBeVisible()
 await expect(page.getByTestId('order-recipient-name')).toHaveValue('Synthetic Recipient')
 await expect(page.getByTestId('kol-smart-address-confirm')).not.toBeChecked()
 await page.locator('.sku-combobox-input').first().fill('E2E-SKU-0001')
 await page.getByRole('option').filter({hasText:'E2E-SKU-0001'}).first().click()
 await page.getByTestId('kol-smart-address-confirm').check()
 await page.getByRole('button',{name:'创建订单',exact:true}).click()
 await expect(page).toHaveURL(/\/kol\/orders\/\d+$/, {timeout:15000})
 console.log('SYNTHETIC_PROFILE_AND_LINKED_ORDER_BROWSER_PASS')
 await guard.assertClean()
})

