import { expect, test } from '@playwright/test'
import { loginThroughUi, syntheticUsers } from '../support/auth-helpers'
import { installBrowserGuards } from '../support/browser-guards'
import path from 'node:path'
test.skip(process.env.BYL_E2E_ALLOCATION_COMPACT!=='1','Requires disposable allocation fixture')
test('ERP1 allocation compact: stock, delete, add, adjacent navigation and submit',async({page,context})=>{
  const guard=await installBrowserGuards(context,page)
  await page.setViewportSize({width:1586,height:928})
  await loginThroughUi(page,syntheticUsers().logisticsOperator)
  await page.goto('/logistics/wait-stock?global_grid=1&search=E2E-COMPACT')
  await expect(page.getByText('E2E-COMPACT-02',{exact:true}).first()).toBeVisible()
  await page.getByRole('button',{name:'查看方案',exact:true}).first().click()
  const modal=page.locator('.plan-modal')
  await expect(modal.locator('.info-card').first()).toContainText('E2E-COMPACT-02')
  await expect(modal.getByRole('button',{name:'上一单'})).toBeDisabled()
  await modal.getByRole('button',{name:'下一单'}).click()
  await expect(modal.locator('.info-card').first()).toContainText('E2E-COMPACT-01')
  await modal.getByRole('button',{name:'上一单'}).click()
  await expect(modal.locator('.info-card').first()).toContainText('E2E-COMPACT-02')
  const table=modal.locator('.manual-table-wrap')
  await expect(table.locator('tbody tr')).toHaveCount(2)
  const stock=table.locator('tbody tr').first().locator('.stock-list')
  await expect(stock).toBeVisible()
  expect(await stock.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' ').length)).toBe(2)
  await expect(table.locator('tbody tr').nth(1)).toContainText('暂无已知有货仓库')
  if(process.env.BYL_E2E_VISUAL_EVIDENCE_DIR) await page.screenshot({path:path.join(process.env.BYL_E2E_VISUAL_EVIDENCE_DIR,'allocation-compact.png')})
  await table.locator('tbody tr').nth(1).getByRole('button',{name:'删除产品'}).click()
  const editor=modal.getByTestId('allocation-item-editor')
  await expect(editor.locator('.allocation-edit-row')).toHaveCount(1)
  await editor.getByRole('button',{name:'保存商品修改'}).click()
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await modal.getByRole('button',{name:/添加产品/}).click()
  const row=editor.locator('.allocation-edit-row').last()
  await row.getByRole('combobox').fill('E2E-COMPACT-C')
  await row.getByRole('option',{name:/E2E-COMPACT-C/}).click()
  await expect(row.getByRole('combobox')).toHaveAttribute('aria-expanded','false')
  await row.getByRole('combobox').press('Tab')
  await editor.getByRole('button',{name:'保存商品修改'}).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table).toContainText('E2E-COMPACT-C')
  for(const row of await table.locator('tbody tr').all()) await row.locator('select').first().selectOption('FACTORY')
  await modal.getByRole('button',{name:/确认人工分配并提交|采用推荐并提交分仓/}).click()
  await expect(modal.locator('.info-card').first()).toContainText('E2E-COMPACT-01',{timeout:15000})
  await guard.assertClean()
  console.log('COMPACT_BROWSER_PASS')
})
