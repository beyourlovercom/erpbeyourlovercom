'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require(path.join(__dirname,'frontend/node_modules/playwright'));
const base='http://127.0.0.1:18786';
(async()=>{
 const key=fs.readFileSync(path.join(__dirname,'private/local-admin-key.txt'),'utf8').trim();
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  page.on('response',r=>{if(r.url().includes('/api/erp/current/orders'))console.log('ORDER_RESPONSE',r.status());});
  page.on('requestfailed',r=>{if(r.url().includes('/api/erp/current/orders'))console.log('ORDER_FAILED',r.failure()?.errorText);});
  await page.goto(base+'/#/auth/login',{waitUntil:'domcontentloaded'});
  await page.locator('input[type=password]').fill(key);
  await page.getByRole('button',{name:'进入 ERP 开发工作台'}).click();
  await page.waitForURL(/#\/erp\/overview/,{timeout:30000,waitUntil:'commit'});
  await page.goto(base+'/#/erp/orders/orders-master');
  await page.waitForTimeout(650);
  const button=page.getByRole('button',{name:'读取当前 Laravel Dev（按角色授权）'}).first();
  await button.waitFor({timeout:16000});
  await button.click();
  await page.waitForTimeout(2500);
  console.log('UI_STATE',JSON.stringify({errors:await page.locator('[role=alert]').allTextContents(),last:(await page.locator('body').innerText()).slice(-500)}));
  await page.getByText('123 条',{exact:false}).first().waitFor({timeout:60000});
  await page.getByText('实际启用的仓库快捷入口 11 个',{exact:false}).first().waitFor({timeout:16000});
  const ownerNav=await page.locator('ul.vben-menu').first().textContent();
  assert.ok(ownerNav?.includes('美东纽约仓')||ownerNav?.includes('us-ny'),'Laravel dynamic warehouse sidebar');
  assert.ok((await page.locator('.ag-cell[col-id=order_no]:visible').count())>0,'real grid cells present');
  assert.equal(await page.getByText('UAT-ORDER-001',{exact:true}).count(),0,'synthetic data not mixed');
  await page.screenshot({path:path.join(__dirname,'r2b-vben-current-owner.png')});
  const role=page.getByLabel('Laravel Dev 测试角色').first();
  await role.selectOption('kol');
  await page.getByText('20 条',{exact:false}).first().waitFor({timeout:20000});
  assert.ok(!(await page.locator('ul.vben-menu').first().textContent())?.includes('库存'),'KOL menu should not contain unauthorized inventory');
  await role.selectOption('manager');
  await page.getByText('41 条',{exact:false}).first().waitFor({timeout:20000});
  await role.selectOption('owner');
  await page.getByText('123 条',{exact:false}).first().waitFor({timeout:20000});
  const filter=page.getByPlaceholder('搜索订单号、仓库或 SKU').first();
  await filter.fill('EX-R2-00042'); await filter.press('Enter');
  await page.getByText('总计 1 条',{exact:false}).first().waitFor({timeout:20000});
  await filter.fill('');await filter.press('Enter');
  await page.getByText('总计 123 条',{exact:false}).first().waitFor({timeout:20000});
  const scope=page.getByLabel('订单读取范围').first();
  await scope.selectOption('customers');
  await page.getByText('82 条',{exact:false}).first().waitFor({timeout:20000});
  await page.getByRole('combobox').last().selectOption('20');
  await page.getByText('第 1 / 5 页',{exact:false}).first().waitFor({timeout:20000});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  assert.equal(overflow,false,'desktop horizontal overflow');
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(450);
  const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  await page.screenshot({path:path.join(__dirname,'r2b-vben-current-mobile.png')});
  assert.equal(mobileOverflow,false,'mobile horizontal overflow');
  console.log('R2B_VBEN_007_BROWSER_PASS Dev123/20/41, role-sidebars, server search1->123, customer82/page20, no-synthetic, desktop+mobile no-overflow');
 }finally{await browser.close()}
})().catch(e=>{console.error('R2B_VBEN_007_BROWSER_FAIL',e.message);process.exitCode=1});